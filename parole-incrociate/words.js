// Calcolo deterministico del numero del giorno dal 1° gennaio 2026
function getDayNumber() {
  const startDate = new Date("2026-01-01T00:00:00");
  const now = new Date();
  const diffTime = Math.abs(now.getTime() - startDate.getTime());
  return Math.floor(diffTime / (1000 * 60 * 60 * 24)) + 1;
}

// Restituisce la parola segreta del giorno per una determinata lunghezza
function getDailyWord(length = 5, dayOffset = 0) {
  const list = PAROLE_INCROCIATE_WORDS[length] || PAROLE_INCROCIATE_WORDS[5];
  const day = getDayNumber() + dayOffset;
  const index = (day * 37 + 13) % list.length;
  return {
    dayNumber: day,
    wordLength: length,
    word: list[index].toUpperCase()
  };
}

// Verifica se una parola è formalmente valida nel vocabolario noto
function isValidWord(word, length = 5) {
  const cleanWord = word.trim().toUpperCase();
  if (cleanWord.length !== length) return false;
  
  const list = PAROLE_INCROCIATE_WORDS[length] || [];
  if (list.includes(cleanWord)) return true;

  if (typeof DICTIONARY !== "undefined" && Array.isArray(DICTIONARY)) {
    if (DICTIONARY.includes(cleanWord)) return true;
  }

  return false;
}